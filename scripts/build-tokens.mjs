// Build tokens/tokens.json (DTCG 2025.10) into CSS custom properties.
//
// Outputs, all in dist/:
//   tokens.css          :root custom properties inside @layer jrl.tokens
//   tokens.json         the DTCG source, copied for tools and agents
//   tokens.resolved.json  every token's final light/dark CSS value, flat, for scripts
//
// Light/dark: the core format has no modes, so a token's dark value lives in
// $extensions["com.joellithgow.modes"].dark. Tokens with one become light-dark().
// Fluid sizes: $extensions["com.joellithgow.fluid"] becomes clamp(min, preferred, $value).
// Aliases ("{color.bg}") become var(--jrl-color-bg) so consumers can override
// one primitive and every role that points at it follows.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SOURCE = "tokens/tokens.json";
const OUT_DIR = "dist";
const PREFIX = "jrl";
const MODES = "com.joellithgow.modes";
const FLUID = "com.joellithgow.fluid";
const ALIAS = /^\{([^}]+)\}$/;

// Walk the tree and collect every token (any object with a $value) by dotted path.
function collectTokens(node, path = [], out = new Map()) {
  if (node && typeof node === "object" && "$value" in node) {
    out.set(path.join("."), node);
    return out;
  }

  for (const [key, child] of Object.entries(node)) {
    if (!key.startsWith("$")) collectTokens(child, [...path, key], out);
  }
  return out;
}

const cssName = (path) => `--${PREFIX}-${path.replaceAll(".", "-")}`;

function aliasTarget(value, tokens, fromPath) {
  const match = typeof value === "string" && value.match(ALIAS);
  if (!match) return null;

  if (!tokens.has(match[1])) {
    throw new Error(`${fromPath}: alias {${match[1]}} does not resolve to a token`);
  }
  return match[1];
}

// Format one DTCG value as CSS. `ref` decides how an alias is written:
// as var() for the stylesheet, or fully resolved for tokens.resolved.json.
function formatValue(type, value, tokens, path, ref) {
  const target = aliasTarget(value, tokens, path);
  if (target) return ref(target);

  switch (type) {
    case "color":
      return value.hex;
    case "dimension":
    case "duration":
      return `${value.value}${value.unit}`;
    case "fontFamily":
      return value.map((f) => (/\s/.test(f) && !f.startsWith("-") ? `'${f}'` : f)).join(", ");
    case "fontWeight":
    case "number":
      return String(value);
    case "cubicBezier":
      return `cubic-bezier(${value.join(", ")})`;
    case "shadow": {
      const part = (v) => formatValue("dimension", v, tokens, path, ref);
      const shadowColor = formatValue("color", value.color, tokens, path, ref);
      return `${part(value.offsetX)} ${part(value.offsetY)} ${part(value.blur)} ${part(value.spread)} ${shadowColor}`;
    }
    default:
      throw new Error(`${path}: unsupported $type "${type}"`);
  }
}

// The value for one mode, before light-dark() or clamp() wrapping.
function modeValue(token, mode, tokens, path, ref) {
  const dark = token.$extensions?.[MODES]?.dark;
  const raw = mode === "dark" && dark !== undefined ? dark : token.$value;
  return formatValue(tokenType(token, tokens, path), raw, tokens, path, ref);
}

// $type, following aliases when a token leaves it to its target.
function tokenType(token, tokens, path) {
  if (token.$type) return token.$type;

  const target = aliasTarget(token.$value, tokens, path);
  if (!target) throw new Error(`${path}: no $type and not an alias`);
  return tokenType(tokens.get(target), tokens, target);
}

function cssValue(token, tokens, path, ref) {
  const fluid = token.$extensions?.[FLUID];
  if (fluid) {
    const dim = (v) => formatValue("dimension", v, tokens, path, ref);
    return `clamp(${dim(fluid.min)}, ${dim(fluid.preferred)}, ${dim(token.$value)})`;
  }

  const light = modeValue(token, "light", tokens, path, ref);
  if (!token.$extensions?.[MODES]) return light;

  const dark = modeValue(token, "dark", tokens, path, ref);
  return light === dark ? light : `light-dark(${light}, ${dark})`;
}

function resolvedValue(path, tokens, mode) {
  const token = tokens.get(path);
  const ref = (target) => resolvedValue(target, tokens, mode);
  if (token.$extensions?.[FLUID]) return cssValue(token, tokens, path, ref);
  return modeValue(token, mode, tokens, path, ref);
}

function main() {
  const source = JSON.parse(readFileSync(SOURCE, "utf8"));
  const tokens = collectTokens(source);
  const asVar = (target) => `var(${cssName(target)})`;

  const declarations = [...tokens].map(([path, token]) => {
    const comment = token.$description ? ` /* ${token.$description} */` : "";
    return `    ${cssName(path)}: ${cssValue(token, tokens, path, asVar)};${comment}`;
  });

  const css = [
    "/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */",
    "",
    "@layer jrl.tokens {",
    "  :root {",
    "    color-scheme: light dark;",
    ...declarations,
    "  }",
    "}",
    "",
  ].join("\n");

  const resolved = Object.fromEntries(
    [...tokens.keys()].map((path) => [
      path,
      { css: cssName(path), light: resolvedValue(path, tokens, "light"), dark: resolvedValue(path, tokens, "dark") },
    ]),
  );

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(`${OUT_DIR}/tokens.css`, css);
  writeFileSync(`${OUT_DIR}/tokens.resolved.json`, JSON.stringify(resolved, null, 2) + "\n");
  copyFileSync(SOURCE, `${OUT_DIR}/tokens.json`);
  console.log(`built ${tokens.size} tokens -> ${OUT_DIR}/tokens.css`);
}

main();
